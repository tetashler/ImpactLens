/** Offline GIS environment is optional for normal application builds. */
import {spawn} from 'node:child_process';
import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {parseBuildingManifest,validateBuilding} from '../lib/buildings/contract.ts';
const args=new Set(process.argv.slice(2));
for(const a of args)if(!['--download','--prototype','--preview','--validate-only'].includes(a))throw new Error('Unknown building preparation option');
const python=process.platform==='win32'?'tmp/phase7c1/venv/Scripts/python.exe':'tmp/phase7c1/venv/bin/python';
async function run(script:string,argv:string[]=[]){await new Promise<void>((resolve,reject)=>{const child=spawn(python,[script,...argv],{stdio:'inherit'});child.on('error',reject);child.on('close',code=>code===0?resolve():reject(new Error('Offline building preparation failed')));});}
if(args.has('--download')){await run('scripts/buildings/acquire.py');process.exit(0);}
if(!args.has('--validate-only'))await run('scripts/buildings/prepare_unified.py',args.has('--prototype')?['--prototype']:[]);
const dir=args.has('--prototype')?'tmp/phase7c1/prototype':'tmp/phase7c1/derived';
const manifest=parseBuildingManifest(JSON.parse(await readFile(`${dir}/unified-manifest.json`,'utf8')));
const ids=new Set<string>(),sources=new Set(manifest.sources!.map(s=>s.id));
for(const chunk of manifest.chunks){
  const bytes=await readFile(`${dir}/${chunk.id}.geojson`);
  if(bytes.length!==chunk.bytes||createHash('sha256').update(bytes).digest('hex')!==chunk.sha256)throw new Error('Chunk integrity failure');
  const data=JSON.parse(bytes.toString());if(data.type!=='FeatureCollection'||data.features.length!==chunk.featureCount)throw new Error('Invalid collection');
  for(const f of data.features){validateBuilding(f);if(!sources.has(f.properties.sourceId)||ids.has(f.id))throw new Error('Invalid source/duplicate ID');ids.add(f.id);}
}
if(ids.size!==manifest.featureCount)throw new Error('Incorrect manifest count');
if(args.has('--preview')){
  // Explicit local preview only. These files are not automatically generated by
  // predev/prebuild and MUST NOT be shipped as a publicly licensed bundle.
  const out='public/geography/buildings-v1';await mkdir(out,{recursive:true});
  for(const c of manifest.chunks)await copyFile(`${dir}/${c.id}.geojson`,`${out}/${c.id}.geojson`);
  await writeFile(`${out}/unified-manifest.json`,JSON.stringify(manifest));
  await copyFile(`${dir}/LICENSING.txt`,`${out}/UNIFIED-LICENSING.txt`);
}
console.log(JSON.stringify({validatedFeatures:ids.size,chunks:manifest.chunks.length,bytes:manifest.chunks.reduce((s,c)=>s+c.bytes,0),preview:args.has('--preview'),distribution:manifest.distribution}));
