export function graphSummary(graph: Graph) {
  const connectivity = analyseConnectivity(graph);
  return {
    stationNodes: graph.stations.size, routingStates: graph.states.size,
    travelEdges: graph.edges.filter(e => e.kind === 'travel').length,
    transferEdges: graph.edges.filter(e => e.kind === 'transfer').length, edges: graph.edges.length,
    stationWeakComponents: connectivity.stationWeakComponents.map(c => c.length),
    stateWeakComponents: connectivity.stateWeakComponents.map(c => c.length),
    stateStrongComponents: connectivity.stateStrongComponents.map(c => c.length),
    unreachableStationPairs: connectivity.unreachableStationPairs,
    unservedStationIds: connectivity.unservedStationIds,
    activeTrips: graph.audit.activeTripCount, acceptedTrips: graph.audit.usedTripCount,
    quarantinedActiveTrips: graph.audit.quarantined.filter(i => graph.audit.activeServices.includes(i.trip.values.service_id)).length,
    invalidTripsAllServices: graph.audit.invalid.length,
  };
}
export const SAMPLE_PAIRS = [
  ['NS4', 'NS2'], ['EW1', 'EW33'], ['NE18', 'CC29'], ['TE1', 'TE29'],
  ['BP2', 'NS2'], ['BP13', 'DT4'], ['EW1', 'NE18'], ['TE1', 'CG2'], ['NE16', 'PW7'],
  ['NS13', 'NS18'], ['NS16', 'NS20'], ['CC33', 'TE23'],
];
export function sampleRoutes(graph: Graph) {
  return SAMPLE_PAIRS.map(([origin, destination]) => {
    const route = shortestPath(graph, origin, destination);
    if (!route) throw new Error(`Representative route unreachable: ${origin} -> ${destination}`);
    const legs: string[] = [];
    let lastLine: string | undefined;
    for (const edge of route.edges) if (edge.kind === 'travel') {
      const line = graph.states.get(edge.from)!.line;
      if (line !== lastLine) { legs.push(line); lastLine = line; }
    }
    return {
      origin, destination,
      originName: graph.stations.get(route.origin)!.name, destinationName: graph.stations.get(route.destination)!.name,
      totalMinutes: Number((route.totalSeconds / 60).toFixed(2)),
      travelMinutes: Number((route.travelSeconds / 60).toFixed(2)),
      transfers: route.edges.filter(e => e.kind === 'transfer').length,
      transferAt: route.edges.filter(e => e.kind === 'transfer').map(e => graph.states.get(e.from)!.stationId),
      lines: legs, stationIds: route.stationIds, edgeIds: route.edges.map(e => e.id),
    };
  });
}
